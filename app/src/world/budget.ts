/* ───────── תקציב ביצועים (כלל perf-budget) ─────────
   האתר צריך להישאר חלק בטלפון גם כשמוסיפים הרבה תוכן. לכן לכל דבר יש תקציב, ובדיקת העולם מתריעה ("perf") כשעוברים אותו:
   - אובייקט אחד: כמה אלמנטים הוא מצייר וכמה נקודות יש בצורות שלו (נמדד בבנייה, o._cost).
   - כל הציור הנייח יחד (הוא נצבע לאריחים: יותר נקודות = צביעה איטית יותר בזום).
   - מה שזז: זמן העדכון הממוצע בפריים (actors.update), ומספר הדברים שזזים.
   המספרים נקבעו לפי המצב הנוכחי (2026-10-08) עם מרווח. אובייקט חדש שחורג: לפשט את הציור, לא להגדיל את התקציב בלי סיבה. */
import { drawCost } from '../core/util';

export const BUDGET = {
  objEls: 300,        // אלמנטים לאובייקט אחד
  objPts: 20000,      // נקודות בצורות של אובייקט אחד
  ptsPerBlock: 113,   // כל הציור הנייח, לפי שטח (החלטת הבעלים 2026-10-09): נקודות למשבצת 100×100. 450 אלף לעולם של 54×74 משבצות; העולם שגדל מקבל תקציב באותה צפיפות
  frameMs: 4,         // זמן עדכון ממוצע של כל מה שזז, בפריים (היום כ-2.3 במחשב; טלפון איטי בערך פי 3)
  buildMs: 1600,      // בניית העולם בטעינה (היום כ-800 במחשב; טלפון איטי בערך פי 3). מדידות לסירוגין עם ציור, או בדיקות של "כל דבר מול כל דבר" – זה מה שמאט
  bootMs: 1800,       // עבודת הדף בטעינה עד שהמפה מוצגת: הבנייה, רשימת הציור והדמויות (2026-10-09: כ-1000 במחשב; לא תלוי בגודל העולם)
  bootChunks: 16,     // אזורים שמצוירים בזמן הטעינה (רק המבט הראשון; השאר ברקע)
  movers: 120,        // דברים שזזים בבת אחת (היום 46: אנשים, חיות, רכבת)
};

/** התקציב לכל הציור הנייח בעולם בגודל הזה (לפי שטח) */
export const totalPts = (B: { x0: number; y0: number; x1: number; y1: number }) => Math.round(BUDGET.ptsPerBlock * (B.x1 - B.x0) * (B.y1 - B.y0) / 1e4);

export const STATIC_COST = { els: 0, pts: 0 };

/** זמן העדכון בפריים: ממוצע נע על 120 הפריימים האחרונים */
export const FRAME = {
  ms: [] as number[],
  add(t: number) { this.ms.push(t); if (this.ms.length > 120) this.ms.shift(); },
  avg() { return this.ms.length ? this.ms.reduce((a, b) => a + b, 0) / this.ms.length : 0; },
};
